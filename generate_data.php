function readList($fileName) {
    $path = __DIR__ . "/" . $fileName;
    if (!file_exists($path)) {
        die("Missing input file: " . htmlspecialchars($fileName));
    }
    $lines = file($path, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    $clean = [];
    foreach ($lines as $line) {
        $line = trim($line);
        if ($line !== "") $clean[] = $line;
    }
    if (count($clean) === 0) {
        die("Input file is empty: " . htmlspecialchars($fileName));
    }
    return $clean;
}

function esc($value) {
    return str_replace("'", "''", $value);
}

$firstNames   = readList("first_names.txt");
$lastNames    = readList("last_names.txt");
$countries    = readList("countries.txt");
$categories   = readList("categories.txt");
$videoTitles  = readList("video_titles.txt");
$comments     = readList("comments.txt");
$youtubeLinks = readList("youtube_links.txt");

$sql = "-- MiniTube seed data generated by generate_data.php from text input files\n\n";

/* USERS */
for ($i = 1; $i <= 120; $i++) {
    $fn = $firstNames[($i - 1) % count($firstNames)];
    $ln = $lastNames[($i - 1) % count($lastNames)];
    $username = strtolower($fn) . $i;
    $plainPassword = "pass" . $i;
    $hashedPassword = password_hash($plainPassword, PASSWORD_BCRYPT, ["cost" => 4]);
    $image = "https://i.pravatar.cc/150?img=" . (($i % 70) + 1);
    $fullName = $fn . " " . $ln;
    $email = strtolower($fn) . $i . "@minitube.com";
    $country = $countries[$i % count($countries)];
    $joined = date("Y-m-d", strtotime("-" . (100 + $i) . " days"));
    $bio = "MiniTube user profile for " . $fullName;

    $sql .= "INSERT INTO USERS (user_id, username, password, user_image, full_name, email, country, joined_on, bio) VALUES ";
    $sql .= "($i, '" . esc($username) . "', '" . esc($hashedPassword) . "', '" . esc($image) . "', '" . esc($fullName) . "', '" . esc($email) . "', '" . esc($country) . "', '$joined', '" . esc($bio) . "');\n";
}

$sql .= "\n";

/* CHANNELS: user owns at most one channel because owner_id is unique */
for ($i = 1; $i <= 70; $i++) {
    $ownerId = $i;
    $image = "https://picsum.photos/seed/channel" . $i . "/300/200";
    $name = "MiniTube Channel " . $i;
    $description = ($i % 7 == 0) ? "" : "This channel creates videos about " . $categories[$i % count($categories)] . ".";
    $created = date("Y-m-d", strtotime("-" . (50 + $i) . " days"));
    $category = $categories[$i % count($categories)];

    $sql .= "INSERT INTO CHANNELS (channel_id, owner_id, channel_image, name, description, created_on, category) VALUES ";
    $sql .= "($i, $ownerId, '" . esc($image) . "', '" . esc($name) . "', '" . esc($description) . "', '$created', '" . esc($category) . "');\n";
}

$sql .= "\n";

/* VIDEOS */
for ($i = 1; $i <= 350; $i++) {
    $channelId = (($i - 1) % 70) + 1;
    $title = $videoTitles[$i % count($videoTitles)] . " #" . $i;
    $description = "Description for video " . $i;
    $url = $youtubeLinks[$i % count($youtubeLinks)];
    $duration = rand(80, 1500);
    $uploaded = date("Y-m-d H:i:s", strtotime("-" . rand(1, 300) . " days -" . rand(1, 23) . " hours"));
    $views = rand(0, 5000);
    $likes = rand(0, 1000);

    $sql .= "INSERT INTO VIDEOS (video_id, channel_id, title, description, url, duration_seconds, uploaded_at, view_count, like_count) VALUES ";
    $sql .= "($i, $channelId, '" . esc($title) . "', '" . esc($description) . "', '" . esc($url) . "', $duration, '$uploaded', $views, $likes);\n";
}

$sql .= "\n";

/* SUBSCRIPTIONS: user 1 follows many channels so the homepage has enough subscribed videos */
$subId = 1;
$usedSubs = [];
for ($channelId = 2; $channelId <= 11; $channelId++) {
    $key = "1-" . $channelId;
    $usedSubs[$key] = true;
    $subscribedAt = date("Y-m-d H:i:s", strtotime("-" . (20 + $channelId) . " days"));
    $sql .= "INSERT INTO SUBSCRIPTIONS (subscription_id, subscriber_id, channel_id, subscribed_at) VALUES ";
    $sql .= "($subId, 1, $channelId, '$subscribedAt');\n";
    $subId++;
}

while ($subId <= 300) {
    $subscriberId = rand(1, 120);
    $channelId = rand(1, 70);
    if ($subscriberId === $channelId) continue; // avoids self-subscription in generated random data
    $key = $subscriberId . "-" . $channelId;
    if (isset($usedSubs[$key])) continue;

    $usedSubs[$key] = true;
    $subscribedAt = date("Y-m-d H:i:s", strtotime("-" . rand(1, 250) . " days"));

    $sql .= "INSERT INTO SUBSCRIPTIONS (subscription_id, subscriber_id, channel_id, subscribed_at) VALUES ";
    $sql .= "($subId, $subscriberId, $channelId, '$subscribedAt');\n";
    $subId++;
}

$sql .= "\n";

/* COMMENTS: 250 top-level comments */
$commentVideoMap = [];
for ($i = 1; $i <= 250; $i++) {
    $videoId = rand(1, 350);
    $commentVideoMap[$i] = $videoId;
    $userId = rand(1, 120);
    $body = $comments[$i % count($comments)];
    $postedAt = date("Y-m-d H:i:s", strtotime("-" . rand(1, 200) . " days -" . rand(1, 23) . " hours"));

    $sql .= "INSERT INTO COMMENTS (comment_id, video_id, user_id, parent_comment_id, body, posted_at) VALUES ";
    $sql .= "($i, $videoId, $userId, NULL, '" . esc($body) . "', '$postedAt');\n";
}

/* 100 replies. Reply video_id always matches parent comment video_id. */
for ($i = 251; $i <= 350; $i++) {
    $parentId = rand(1, 250);
    $videoId = $commentVideoMap[$parentId];
    $userId = rand(1, 120);
    $body = "Reply comment: " . $comments[$i % count($comments)];
    $postedAt = date("Y-m-d H:i:s", strtotime("-" . rand(1, 100) . " days -" . rand(1, 23) . " hours"));

    $sql .= "INSERT INTO COMMENTS (comment_id, video_id, user_id, parent_comment_id, body, posted_at) VALUES ";
    $sql .= "($i, $videoId, $userId, $parentId, '" . esc($body) . "', '$postedAt');\n";
}

$sql .= "\n";

/* VIDEO LIKES */
$likeId = 1;
$usedLikes = [];
while ($likeId <= 260) {
    $userId = rand(1, 120);
    $videoId = rand(1, 350);
    $key = $userId . "-" . $videoId;
    if (isset($usedLikes[$key])) continue;
    $usedLikes[$key] = true;
    $likedAt = date("Y-m-d H:i:s", strtotime("-" . rand(1, 90) . " days -" . rand(1, 23) . " hours"));
    $sql .= "INSERT INTO VIDEO_LIKES (like_id, user_id, video_id, liked_at) VALUES ";
    $sql .= "($likeId, $userId, $videoId, '$likedAt');\n";
    $likeId++;
}

$sql .= "\n";

/* WATCH HISTORY */
$historyId = 1;
$usedHistory = [];
for ($videoId = 1; $videoId <= 5; $videoId++) {
    $usedHistory["1-" . $videoId] = true;
    $watchedAt = date("Y-m-d H:i:s", strtotime("-" . $videoId . " hours"));
    $sql .= "INSERT INTO WATCH_HISTORY (history_id, user_id, video_id, watched_at) VALUES ";
    $sql .= "($historyId, 1, $videoId, '$watchedAt');\n";
    $historyId++;
}

while ($historyId <= 260) {
    $userId = rand(1, 120);
    $videoId = rand(1, 350);
    $key = $userId . "-" . $videoId;
    if (isset($usedHistory[$key])) continue;
    $usedHistory[$key] = true;
    $watchedAt = date("Y-m-d H:i:s", strtotime("-" . rand(1, 60) . " days -" . rand(1, 23) . " hours"));
    $sql .= "INSERT INTO WATCH_HISTORY (history_id, user_id, video_id, watched_at) VALUES ";
    $sql .= "($historyId, $userId, $videoId, '$watchedAt');\n";
    $historyId++;
}

file_put_contents(__DIR__ . "/seed.sql", $sql);

header("Location: install.php");
exit();
